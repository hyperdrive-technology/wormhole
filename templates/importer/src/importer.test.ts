import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createImportContext, ImporterHost, VirtualFileTree, type ImportResult } from '@wormhole/sdk';
import { describe, expect, it } from 'vitest';

import importer, { CAPABILITY_ID, Code } from './index.js';
import { checkType, initialValueProblem, nameProblem, sanitizeComment } from './tags.js';

const fixturesDir = join(dirname(fileURLToPath(import.meta.url)), '../fixtures');
const plantTags = readFileSync(join(fixturesDir, 'plant-tags.csv'), 'utf8');

type Files = Record<string, string | Uint8Array>;

function tree(files: Files): VirtualFileTree {
  const loaded = VirtualFileTree.fromEntries(Object.entries(files).map(([path, content]) => ({ path, content })));
  expect(loaded.fatal).toBe(false);
  return loaded.tree;
}

/** Runs import() directly with a fresh context, the way a host would. */
async function runImport(files: Files, signal?: AbortSignal): Promise<ImportResult> {
  const handle = createImportContext(signal ? { signal } : {});
  try {
    return await importer.import({ files: tree(files), capabilityId: CAPABILITY_ID, options: {} }, handle.context);
  } finally {
    handle.dispose();
  }
}

const codes = (result: ImportResult): string[] => result.diagnostics.map((d) => d.code);
const HEADER = 'name,type,initial,comment\n';

describe('detect', () => {
  it('returns null when there is no .csv file', () => {
    expect(importer.detect({ files: tree({ 'main.st': 'PROGRAM Main END_PROGRAM' }) })).toBeNull();
    expect(importer.detect({ files: VirtualFileTree.empty() })).toBeNull();
  });

  it('is confident about a name,type header (any case, extra columns, BOM)', () => {
    for (const header of ['name,type\n', 'Comment,TYPE,unit,Name\n', '﻿name,type,initial,comment\n', '"name","type"\n']) {
      expect(importer.detect({ files: tree({ 'tags.csv': header }) })).toEqual({
        capabilityId: CAPABILITY_ID,
        confidence: 0.9,
        reason: 'tags.csv has a name,type tag-list header',
      });
    }
  });

  it('is unsure about other .csv files', () => {
    for (const content of ['id,value\n1,2\n', '', new Uint8Array([0, 1, 2, 3])]) {
      expect(importer.detect({ files: tree({ 'data.csv': content }) })?.confidence).toBe(0.2);
    }
  });

  it('finds a tag list among other CSVs, deterministically', () => {
    const files = tree({ 'a.csv': 'x,y\n', 'b.CSV': plantTags, 'readme.txt': 'hi' });
    const first = importer.detect({ files });
    expect(first?.confidence).toBe(0.9);
    expect(first?.reason).toBe('b.CSV has a name,type tag-list header');
    expect(importer.detect({ files })).toEqual(first);
  });

  it('only sniffs the head of a few files', () => {
    const files: Files = {};
    for (let index = 0; index < 10; index += 1) files[`f${index}.csv`] = 'x'.repeat(100_000);
    let bytesRead = 0;
    const observed = tree(files).withReadObserver((_, bytes) => {
      bytesRead += bytes;
    });
    importer.detect({ files: observed });
    expect(bytesRead).toBeLessThanOrEqual(4 * 4096);
  });
});

describe('import', () => {
  it('converts a tag list into a VAR_GLOBAL block', async () => {
    const result = await runImport({ 'plant-tags.csv': plantTags });
    expect(result.sources).toEqual({
      'sources/plant-tags.plc': [
        '(* Generated by example.csv-tags-importer 0.1.0 from plant-tags.csv. *)',
        'VAR_GLOBAL',
        '    Motor_Run : BOOL := FALSE; (* Main conveyor motor running *)',
        '    Tank_Level : REAL := 0.0; (* Tank level, percent of span *)',
        "    Batch_Name : STRING[32] := 'BATCH-001'; (* Operator-visible \"batch\" name *)",
        '    Fill_Time : TIME := T#30s; (* Fill timeout *)',
        '    Alarm_Mask : WORD := 16#00FF;',
        'END_VAR',
        '',
      ].join('\n'),
    });
    expect(result.diagnostics).toEqual([]);
    expect(result.preservation).toBeUndefined();
    expect(result.summary).toEqual({
      message: 'Converted 5 tag(s) from 1 of 1 CSV file(s); 0 row(s) rejected, 0 file(s) skipped.',
      stats: { csvFiles: 1, filesConverted: 1, filesSkipped: 0, tags: 5, rowsRejected: 0, valuesUpgraded: 0 },
    });
  });

  it('writes one source per CSV, keeping directories, and ignores other files', async () => {
    const result = await runImport({
      'area1/pumps.csv': `${HEADER}P1,BOOL,,\n`,
      'area2/valves.CSV': `${HEADER}V1,BOOL,,\n`,
      'notes.txt': 'not a tag list',
    });
    expect(Object.keys(result.sources)).toEqual(['sources/area1/pumps.plc', 'sources/area2/valves.plc']);
    expect(result.sources['sources/area1/pumps.plc']).toContain('    P1 : BOOL;\n');
  });

  it('treats CRLF exactly like LF and says so', async () => {
    const lf = await runImport({ 'plant-tags.csv': plantTags });
    const crlf = await runImport({ 'plant-tags.csv': plantTags.replace(/\n/g, '\r\n') });
    expect(crlf.sources).toEqual(lf.sources);
    expect(crlf.diagnostics).toEqual([
      expect.objectContaining({ code: Code.LINE_ENDINGS_NORMALIZED, severity: 'info', source: { path: 'plant-tags.csv' } }),
    ]);
  });

  it('handles quoted fields with commas, quotes and line breaks', async () => {
    const result = await runImport({
      'q.csv': `${HEADER}"Speed",REAL,"1.5","rpm, measured at ""shaft"""\nNote,BOOL,,"line one\nline two"\nAfter,INT,,\n`,
    });
    const source = result.sources['sources/q.plc'];
    expect(source).toContain('    Speed : REAL := 1.5; (* rpm, measured at "shaft" *)\n');
    expect(source).toContain('    Note : BOOL; (* line one line two *)\n');
    expect(source).toContain('    After : INT;\n');
    expect(result.diagnostics).toEqual([
      expect.objectContaining({ code: Code.COMMENT_SANITIZED, source: { path: 'q.csv', startLine: 3 } }),
    ]);
  });

  it('rejects bad rows with located diagnostics and preserves them verbatim', async () => {
    const csv = [
      'name,type,initial,comment',
      'Good,INT,1,ok',
      '1Bad,INT,,starts with a digit',
      'Unknown_Type,FOO,,',
      'Bad_Init,INT,1; Evil := 2,',
      'END_VAR,BOOL,,reserved word',
      ',BOOL,,missing name',
      'Also_Good,BOOL,TRUE,',
      'Quote,STRING,\'unterminated,',
    ].join('\n');
    const result = await runImport({ 'tags/bad.csv': csv });
    expect(result.sources['sources/tags/bad.plc']).toBe(
      [
        '(* Generated by example.csv-tags-importer 0.1.0 from tags/bad.csv. *)',
        'VAR_GLOBAL',
        '    Good : INT := 1; (* ok *)',
        '    Also_Good : BOOL := TRUE;',
        'END_VAR',
        '',
      ].join('\n'),
    );
    const invalid = result.diagnostics.filter((d) => d.code === Code.INVALID_ROW);
    expect(invalid.map((d) => [d.severity, d.source?.startLine])).toEqual([
      ['error', 3],
      ['error', 4],
      ['error', 5],
      ['error', 6],
      ['error', 7],
      ['error', 9],
    ]);
    expect(invalid.every((d) => d.source?.path === 'tags/bad.csv')).toBe(true);
    expect(invalid[0]?.message).toMatch(/"1Bad" is not a valid IEC 61131-3 identifier/);
    expect(invalid[1]?.message).toMatch(/type "FOO" is not a supported elementary type/);
    expect(invalid[2]?.message).toMatch(/initial value "1; Evil := 2" is not a single literal/);
    expect(invalid[3]?.message).toMatch(/"END_VAR" is a reserved word/);
    expect(invalid[4]?.message).toMatch(/the name is empty/);
    expect(result.preservation).toEqual({
      'preservation/tags/bad.csv.rejected.csv': [
        'name,type,initial,comment',
        '1Bad,INT,,starts with a digit',
        'Unknown_Type,FOO,,',
        'Bad_Init,INT,1; Evil := 2,',
        'END_VAR,BOOL,,reserved word',
        ',BOOL,,missing name',
        "Quote,STRING,'unterminated,",
        '',
      ].join('\n'),
    });
    expect(result.summary.stats).toMatchObject({ tags: 2, rowsRejected: 6 });
  });

  it('reports malformed CSV records and keeps them in the sidecar in line order', async () => {
    const result = await runImport({ 'm.csv': `${HEADER}"A"x,BOOL,,\nB,BOOL,,\n9C,BOOL,,\nD,BOOL,,"open\n` });
    expect(result.sources['sources/m.plc']).toContain('    B : BOOL;\n');
    expect(result.diagnostics.map((d) => [d.code, d.source?.startLine])).toEqual([
      [Code.MALFORMED_ROW, 2],
      [Code.INVALID_ROW, 4],
      [Code.MALFORMED_ROW, 5],
    ]);
    expect(result.preservation?.['preservation/m.csv.rejected.csv']).toBe(
      'name,type,initial,comment\n"A"x,BOOL,,\n9C,BOOL,,\nD,BOOL,,"open\n',
    );
  });

  it('keeps the first of duplicate tag names, case-insensitively and across files', async () => {
    const result = await runImport({
      'a.csv': `${HEADER}Pump,BOOL,,first\nPUMP,INT,,same name in upper case\n`,
      'b.csv': `${HEADER}pump,REAL,,other file\nValve,BOOL,,\n`,
    });
    expect(result.sources['sources/a.plc']).toContain('    Pump : BOOL; (* first *)\n');
    expect(result.sources['sources/a.plc']).not.toContain('PUMP');
    expect(result.sources['sources/b.plc']).not.toContain('pump');
    const duplicates = result.diagnostics.filter((d) => d.code === Code.DUPLICATE_TAG);
    expect(duplicates.map((d) => [d.severity, d.source])).toEqual([
      ['error', { path: 'a.csv', startLine: 3 }],
      ['error', { path: 'b.csv', startLine: 2 }],
    ]);
    expect(duplicates[1]?.message).toBe('b.csv:2: tag pump is already declared at a.csv:2; the first declaration was kept.');
    expect(Object.keys(result.preservation ?? {})).toEqual([
      'preservation/a.csv.rejected.csv',
      'preservation/b.csv.rejected.csv',
    ]);
  });

  it('neutralises comment delimiters so a comment cannot end early', async () => {
    const result = await runImport({
      'c.csv': `${HEADER}A,BOOL,,"ends *) here; B := TRUE; (* again"\nB,BOOL,,(*)\nC,BOOL,,**))\n`,
    });
    const lines = (result.sources['sources/c.plc'] ?? '').split('\n').filter((line) => line.startsWith('    '));
    expect(lines).toEqual([
      '    A : BOOL; (* ends * ) here; B := TRUE; ( * again *)',
      '    B : BOOL; (* ( * ) *)',
      '    C : BOOL; (* ** )) *)',
    ]);
    for (const line of lines) {
      // Exactly one opener and one closer: the comment is the declaration's last token.
      expect(line.split('(*')).toHaveLength(2);
      expect(line.split('*)')).toHaveLength(2);
      expect(line.endsWith('*)')).toBe(true);
    }
    expect(result.diagnostics.filter((d) => d.code === Code.COMMENT_SANITIZED)).toHaveLength(3);
  });

  it('upgrades legacy octal initial values through ctx.migrate', async () => {
    const result = await runImport({ 'legacy.csv': `${HEADER}Mode,WORD,8#17,\nText,STRING,'8#17',\n` });
    expect(result.sources['sources/legacy.plc']).toContain('    Mode : WORD := 16#F;\n');
    expect(result.sources['sources/legacy.plc']).toContain("    Text : STRING := '8#17';\n");
    expect(result.diagnostics).toEqual([
      expect.objectContaining({ code: 'WORMHOLE_OCTAL_TO_HEX', severity: 'info', source: { path: 'legacy.csv', startLine: 2 } }),
    ]);
    expect(result.summary.stats?.valuesUpgraded).toBe(1);
  });

  it('decodes non-UTF-8 input as Windows-1252 and warns', async () => {
    // "Temp,REAL,,Temperature °C" with ° as the single Windows-1252 byte 0xB0.
    const bytes = new Uint8Array([...new TextEncoder().encode(`${HEADER}Temp,REAL,,Temperature `), 0xb0, 0x43, 0x0a]);
    const result = await runImport({ 'w.csv': bytes });
    expect(result.sources['sources/w.plc']).toContain('    Temp : REAL; (* Temperature °C *)\n');
    expect(codes(result)).toEqual([Code.ENCODING_GUESSED]);
    expect(result.diagnostics[0]?.severity).toBe('warning');
  });

  it('skips binary files with an error', async () => {
    const result = await runImport({ 'bin.csv': new Uint8Array([0x6e, 0x61, 0x00, 0x6d, 0x65]), 'ok.csv': `${HEADER}A,BOOL,,\n` });
    expect(Object.keys(result.sources)).toEqual(['sources/ok.plc']);
    expect(result.diagnostics).toEqual([
      expect.objectContaining({ code: Code.BINARY_FILE, severity: 'error', source: { path: 'bin.csv' } }),
    ]);
    expect(result.summary.stats).toMatchObject({ filesConverted: 1, filesSkipped: 1 });
  });

  it('reports an error and returns no sources when there is no CSV', async () => {
    for (const files of [{}, { 'readme.txt': 'hello' }] as Files[]) {
      const result = await runImport(files);
      expect(result.sources).toEqual({});
      expect(result.diagnostics).toEqual([expect.objectContaining({ code: Code.NO_INPUT, severity: 'error' })]);
      expect(result.summary.message).toBe('No CSV tag lists found.');
    }
  });

  it('warns about empty files and files without convertible tags', async () => {
    const result = await runImport({ 'empty.csv': '', 'header-only.csv': HEADER });
    expect(result.sources).toEqual({});
    expect(codes(result)).toEqual([Code.EMPTY_FILE, Code.NO_TAGS]);
    expect(result.diagnostics.every((d) => d.severity === 'warning')).toBe(true);
  });

  it('preserves a whole file whose header lacks name and type', async () => {
    const text = 'id,value\n1,2\n';
    const result = await runImport({ 'data.csv': text });
    expect(result.sources).toEqual({});
    expect(result.diagnostics).toEqual([
      expect.objectContaining({ code: Code.MISSING_COLUMNS, severity: 'error', source: { path: 'data.csv', startLine: 1 } }),
    ]);
    expect(result.preservation).toEqual({ 'preservation/data.csv.rejected.csv': text });
  });

  it('warns about duplicate header columns and uses the first', async () => {
    const result = await runImport({ 'd.csv': 'name,type,name\nFirst,BOOL,Second\n' });
    expect(result.sources['sources/d.plc']).toContain('    First : BOOL;\n');
    expect(codes(result)).toEqual([Code.DUPLICATE_COLUMN]);
  });

  // A skipped file would leave a "succeeded" archive missing its tags (GPT review on
  // wormhole#1), so an output that collides or has no usable name fails the whole import.
  it('fails instead of dropping outputs that would collide or have no name', async () => {
    const result = await runImport({ 'a.csv': `${HEADER}A,BOOL,,\n`, 'A.CSV': `${HEADER}B,BOOL,,\n`, 'x/.csv': `${HEADER}C,BOOL,,\n` });
    expect(result.sources).toEqual({});
    expect(codes(result).sort()).toEqual([Code.OUTPUT_COLLISION, Code.UNPORTABLE_PATH].sort());
    expect(result.summary.message).toMatch(/^Project not imported/);
    expect(result.summary.stats).toMatchObject({ filesLost: 2, filesConverted: 0 });
  });

  it.each([
    ['a case-only collision', { 'A.CSV': `${HEADER}Pump,BOOL,,\n`, 'a.csv': `${HEADER}Valve,BOOL,,\n` }],
    ['an unportable output path', { 'ok.csv': `${HEADER}Pump,BOOL,,\n`, 'bad:name.csv': `${HEADER}Valve,BOOL,,\n` }],
  ])('fails through ImporterHost with NO_SOURCES on %s', async (_, files) => {
    const host = new ImporterHost();
    host.register(importer);
    const loaded = VirtualFileTree.fromEntries(Object.entries(files).map(([path, content]) => ({ path, content })));
    const outcome = await host.run({ capabilityId: CAPABILITY_ID, input: loaded.tree });
    expect(outcome.status).toBe('failed');
    expect(outcome.failure?.code).toBe('NO_SOURCES');
    expect(outcome.archive).toBeUndefined();
  });

  it('is deterministic', async () => {
    const files = { 'b.csv': `${HEADER}B,BOOL,,\nB,INT,,dup\n`, 'a.csv': plantTags };
    expect(await runImport(files)).toEqual(await runImport(files));
  });

  it('stops with the abort reason when the signal is already aborted', async () => {
    const controller = new AbortController();
    const reason = new DOMException('cancelled by test', 'AbortError');
    controller.abort(reason);
    await expect(runImport({ 'plant-tags.csv': plantTags }, controller.signal)).rejects.toBe(reason);
  });
});

