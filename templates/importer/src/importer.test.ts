describe('tag helpers', () => {
  it('validates names', () => {
    expect(nameProblem('Motor_1')).toBeUndefined();
    expect(nameProblem('_hidden')).toBeUndefined();
    expect(nameProblem('Has Space')).toMatch(/not a valid/);
    expect(nameProblem('Ünicode')).toMatch(/not a valid/);
    expect(nameProblem('int')).toMatch(/reserved/);
  });

  it('normalises and checks types', () => {
    expect(checkType('dint')).toEqual({ ok: true, type: 'DINT' });
    expect(checkType('string[80]')).toEqual({ ok: true, type: 'STRING[80]' });
    expect(checkType('STRING[0]').ok).toBe(false);
    expect(checkType('ARRAY[1..2] OF INT').ok).toBe(false);
    expect(checkType('').ok).toBe(false);
  });

  it('accepts single literals only', () => {
    for (const ok of ['', '0', '-1.5E3', '16#FF', 'TRUE', 'T#1h_2m', 'DT#2026-01-01-00:00:00', "'it$'s'", '"$N"']) {
      expect(initialValueProblem(ok), ok).toBeUndefined();
    }
    for (const bad of ['1;', '1 (* x *)', "'a", "'a' + 'b'", 'a\nb', '1 // x']) {
      expect(initialValueProblem(bad), bad).toBeDefined();
    }
  });

  it('sanitises comments', () => {
    expect(sanitizeComment('plain')).toEqual({ text: 'plain', changed: false });
    expect(sanitizeComment('  padded  ')).toEqual({ text: 'padded', changed: false });
    expect(sanitizeComment('a*)b(*c\td')).toEqual({ text: 'a* )b( *c d', changed: true });
  });
});
